import { sql } from "drizzle-orm";
import {
  boolean,
  char,
  check,
  date,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
  varchar,
} from "drizzle-orm/pg-core";
import { workspaceCatalogRecords } from "./catalog.schema";
import { users, workspaces } from "./schema";

export const workspaceVendors = pgTable(
  "workspace_vendors",
  {
    workspaceId: uuid("workspace_id").notNull().references(() => workspaces.id, { onDelete: "cascade" }),
    id: uuid("id").notNull(),
    code: varchar("code", { length: 80 }).notNull(),
    displayName: varchar("display_name", { length: 240 }).notNull(),
    legalName: varchar("legal_name", { length: 240 }),
    capabilities: varchar("capabilities", { length: 24 }).array().notNull().default(sql`'{}'::varchar[]`),
    registrationNumber: varchar("registration_number", { length: 120 }),
    taxRegistrationNumber: varchar("tax_registration_number", { length: 120 }),
    defaultCurrency: char("default_currency", { length: 3 }),
    website: varchar("website", { length: 500 }),
    notes: text("notes").notNull().default(""),
    status: varchar("status", { length: 16 }).notNull().default("draft"),
    archivedReason: varchar("archived_reason", { length: 500 }),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    archivedBy: uuid("archived_by").references(() => users.id),
    version: integer("version").notNull().default(1),
    createdBy: uuid("created_by").notNull().references(() => users.id),
    updatedBy: uuid("updated_by").notNull().references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ name: "workspace_vendors_pk", columns: [table.workspaceId, table.id] }),
    uniqueIndex("workspace_vendors_code_uidx").on(table.workspaceId, sql`lower(${table.code})`),
    uniqueIndex("workspace_vendors_registration_uidx")
      .on(table.workspaceId, sql`lower(btrim(${table.registrationNumber}))`)
      .where(sql`${table.registrationNumber} IS NOT NULL`),
    uniqueIndex("workspace_vendors_tax_registration_uidx")
      .on(table.workspaceId, sql`lower(btrim(${table.taxRegistrationNumber}))`)
      .where(sql`${table.taxRegistrationNumber} IS NOT NULL`),
    index("workspace_vendors_name_idx").on(table.workspaceId, sql`lower(${table.displayName})`, table.id),
    index("workspace_vendors_status_idx").on(table.workspaceId, table.status, table.updatedAt),
    check("workspace_vendors_code_check", sql`${table.code} ~ '^[A-Z0-9][A-Z0-9_-]{0,79}$'`),
    check("workspace_vendors_name_check", sql`length(btrim(${table.displayName})) BETWEEN 1 AND 240`),
    check("workspace_vendors_status_check", sql`${table.status} IN ('draft','active','archived')`),
    check(
      "workspace_vendors_capabilities_check",
      sql`${table.capabilities} <@ ARRAY['materials','services','subcontracting','manufacturing','logistics','other']::varchar[]`,
    ),
    check("workspace_vendors_active_capability_check", sql`${table.status} <> 'active' OR cardinality(${table.capabilities}) > 0`),
    check("workspace_vendors_currency_check", sql`${table.defaultCurrency} IS NULL OR ${table.defaultCurrency} ~ '^[A-Z]{3}$'`),
    check(
      "workspace_vendors_archive_check",
      sql`(${table.status} = 'archived' AND ${table.archivedReason} IS NOT NULL AND ${table.archivedAt} IS NOT NULL AND ${table.archivedBy} IS NOT NULL) OR (${table.status} <> 'archived' AND ${table.archivedReason} IS NULL AND ${table.archivedAt} IS NULL AND ${table.archivedBy} IS NULL)`,
    ),
    check("workspace_vendors_version_check", sql`${table.version} > 0`),
  ],
);

export const workspaceVendorSites = pgTable(
  "workspace_vendor_sites",
  {
    workspaceId: uuid("workspace_id").notNull(),
    vendorId: uuid("vendor_id").notNull(),
    id: uuid("id").notNull(),
    name: varchar("name", { length: 180 }).notNull(),
    siteType: varchar("site_type", { length: 20 }).notNull(),
    contactName: varchar("contact_name", { length: 180 }),
    email: varchar("email", { length: 320 }),
    phone: varchar("phone", { length: 80 }),
    addressLine1: varchar("address_line1", { length: 240 }),
    addressLine2: varchar("address_line2", { length: 240 }),
    locality: varchar("locality", { length: 160 }),
    region: varchar("region", { length: 160 }),
    postalCode: varchar("postal_code", { length: 40 }),
    countryCode: char("country_code", { length: 2 }),
    isPrimary: boolean("is_primary").notNull().default(false),
    status: varchar("status", { length: 16 }).notNull().default("active"),
    archivedReason: varchar("archived_reason", { length: 500 }),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    archivedBy: uuid("archived_by").references(() => users.id),
    version: integer("version").notNull().default(1),
    createdBy: uuid("created_by").notNull().references(() => users.id),
    updatedBy: uuid("updated_by").notNull().references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ name: "workspace_vendor_sites_pk", columns: [table.workspaceId, table.id] }),
    unique("workspace_vendor_sites_vendor_identity_uq").on(table.workspaceId, table.vendorId, table.id),
    foreignKey({
      name: "workspace_vendor_sites_vendor_fk",
      columns: [table.workspaceId, table.vendorId],
      foreignColumns: [workspaceVendors.workspaceId, workspaceVendors.id],
    }).onDelete("cascade"),
    uniqueIndex("workspace_vendor_sites_primary_uidx")
      .on(table.workspaceId, table.vendorId)
      .where(sql`${table.status} = 'active' AND ${table.isPrimary}`),
    index("workspace_vendor_sites_vendor_idx").on(table.workspaceId, table.vendorId, table.status, table.name),
    check("workspace_vendor_sites_name_check", sql`length(btrim(${table.name})) BETWEEN 1 AND 180`),
    check("workspace_vendor_sites_type_check", sql`${table.siteType} IN ('branch','store','office','warehouse','factory','other')`),
    check("workspace_vendor_sites_status_check", sql`${table.status} IN ('active','archived')`),
    check("workspace_vendor_sites_country_check", sql`${table.countryCode} IS NULL OR ${table.countryCode} ~ '^[A-Z]{2}$'`),
    check(
      "workspace_vendor_sites_archive_check",
      sql`(${table.status} = 'archived' AND NOT ${table.isPrimary} AND ${table.archivedReason} IS NOT NULL AND ${table.archivedAt} IS NOT NULL AND ${table.archivedBy} IS NOT NULL) OR (${table.status} = 'active' AND ${table.archivedReason} IS NULL AND ${table.archivedAt} IS NULL AND ${table.archivedBy} IS NULL)`,
    ),
    check("workspace_vendor_sites_version_check", sql`${table.version} > 0`),
  ],
);

export const workspaceSupplierOffers = pgTable(
  "workspace_supplier_offers",
  {
    workspaceId: uuid("workspace_id").notNull(),
    id: uuid("id").notNull(),
    vendorId: uuid("vendor_id").notNull(),
    vendorSiteId: uuid("vendor_site_id"),
    catalogRecordId: uuid("catalog_record_id").notNull(),
    unitRecordId: uuid("unit_record_id"),
    supplierSku: varchar("supplier_sku", { length: 120 }),
    amount: numeric("amount", { precision: 20, scale: 6 }),
    currency: char("currency", { length: 3 }),
    quantityFrom: numeric("quantity_from", { precision: 20, scale: 6 }),
    minimumOrderQuantity: numeric("minimum_order_quantity", { precision: 20, scale: 6 }),
    orderMultiple: numeric("order_multiple", { precision: 20, scale: 6 }),
    leadTimeDays: integer("lead_time_days"),
    effectiveFrom: date("effective_from"),
    effectiveTo: date("effective_to"),
    sourceType: varchar("source_type", { length: 24 }),
    sourceReference: varchar("source_reference", { length: 240 }),
    taxTreatment: varchar("tax_treatment", { length: 20 }).notNull().default("unconfirmed"),
    inclusions: varchar("inclusions", { length: 24 }).array().notNull().default(sql`'{}'::varchar[]`),
    terms: text("terms").notNull().default(""),
    notes: text("notes").notNull().default(""),
    status: varchar("status", { length: 16 }).notNull().default("draft"),
    archivedReason: varchar("archived_reason", { length: 500 }),
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    archivedBy: uuid("archived_by").references(() => users.id),
    version: integer("version").notNull().default(1),
    createdBy: uuid("created_by").notNull().references(() => users.id),
    updatedBy: uuid("updated_by").notNull().references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ name: "workspace_supplier_offers_pk", columns: [table.workspaceId, table.id] }),
    foreignKey({ name: "workspace_supplier_offers_vendor_fk", columns: [table.workspaceId, table.vendorId], foreignColumns: [workspaceVendors.workspaceId, workspaceVendors.id] }),
    foreignKey({ name: "workspace_supplier_offers_site_fk", columns: [table.workspaceId, table.vendorId, table.vendorSiteId], foreignColumns: [workspaceVendorSites.workspaceId, workspaceVendorSites.vendorId, workspaceVendorSites.id] }),
    foreignKey({ name: "workspace_supplier_offers_catalog_fk", columns: [table.workspaceId, table.catalogRecordId], foreignColumns: [workspaceCatalogRecords.workspaceId, workspaceCatalogRecords.id] }),
    foreignKey({ name: "workspace_supplier_offers_unit_fk", columns: [table.workspaceId, table.unitRecordId], foreignColumns: [workspaceCatalogRecords.workspaceId, workspaceCatalogRecords.id] }),
    index("workspace_supplier_offers_catalog_idx").on(table.workspaceId, table.catalogRecordId, table.status, table.effectiveFrom),
    index("workspace_supplier_offers_vendor_idx").on(table.workspaceId, table.vendorId, table.status, table.updatedAt),
    check("workspace_supplier_offers_status_check", sql`${table.status} IN ('draft','active','archived')`),
    check("workspace_supplier_offers_amount_check", sql`${table.amount} IS NULL OR ${table.amount} >= 0`),
    check("workspace_supplier_offers_currency_check", sql`${table.currency} IS NULL OR ${table.currency} ~ '^[A-Z]{3}$'`),
    check("workspace_supplier_offers_quantity_from_check", sql`${table.quantityFrom} IS NULL OR ${table.quantityFrom} > 0`),
    check("workspace_supplier_offers_minimum_order_check", sql`${table.minimumOrderQuantity} IS NULL OR ${table.minimumOrderQuantity} > 0`),
    check("workspace_supplier_offers_multiple_check", sql`${table.orderMultiple} IS NULL OR ${table.orderMultiple} > 0`),
    check("workspace_supplier_offers_lead_time_check", sql`${table.leadTimeDays} IS NULL OR ${table.leadTimeDays} BETWEEN 0 AND 3650`),
    check("workspace_supplier_offers_dates_check", sql`${table.effectiveFrom} IS NULL OR ${table.effectiveTo} IS NULL OR ${table.effectiveTo} >= ${table.effectiveFrom}`),
    check("workspace_supplier_offers_source_check", sql`${table.sourceType} IS NULL OR ${table.sourceType} IN ('vendor_quote','price_list','contract','verbal_confirmation','estimate','included')`),
    check("workspace_supplier_offers_tax_check", sql`${table.taxTreatment} IN ('unconfirmed','exclusive','inclusive','not_applicable')`),
    check("workspace_supplier_offers_inclusions_check", sql`${table.inclusions} <@ ARRAY['delivery','unloading','installation','packaging','warranty','other']::varchar[]`),
    check("workspace_supplier_offers_zero_check", sql`${table.amount} IS NULL OR (${table.amount}=0 AND ${table.sourceType} IS NOT DISTINCT FROM 'included') OR (${table.amount}>0 AND ${table.sourceType} IS DISTINCT FROM 'included')`),
    check("workspace_supplier_offers_active_check", sql`${table.status}<>'active' OR (${table.unitRecordId} IS NOT NULL AND ${table.amount} IS NOT NULL AND ${table.currency} IS NOT NULL AND ${table.effectiveFrom} IS NOT NULL AND ${table.sourceType} IS NOT NULL AND ${table.sourceReference} IS NOT NULL AND length(btrim(${table.sourceReference}))>0 AND ${table.taxTreatment}<>'unconfirmed')`),
    check("workspace_supplier_offers_archive_check", sql`(${table.status}='archived' AND ${table.archivedReason} IS NOT NULL AND length(btrim(${table.archivedReason}))>0 AND ${table.archivedAt} IS NOT NULL AND ${table.archivedBy} IS NOT NULL) OR (${table.status}<>'archived' AND ${table.archivedReason} IS NULL AND ${table.archivedAt} IS NULL AND ${table.archivedBy} IS NULL)`),
    check("workspace_supplier_offers_version_check", sql`${table.version}>0`),
  ],
);

export const workspaceSupplierOfferCommands = pgTable(
  "workspace_supplier_offer_commands",
  {
    workspaceId: uuid("workspace_id").notNull(),
    requestId: uuid("request_id").notNull(),
    offerId: uuid("offer_id").notNull(),
    action: varchar("action", { length: 20 }).notNull(),
    requestHash: char("request_hash", { length: 64 }).notNull(),
    response: jsonb("response").$type<Record<string, unknown>>().notNull(),
    actorUserId: uuid("actor_user_id").notNull().references(() => users.id),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    primaryKey({ name: "workspace_supplier_offer_commands_pk", columns: [table.workspaceId, table.requestId] }),
    foreignKey({ name: "workspace_supplier_offer_commands_offer_fk", columns: [table.workspaceId, table.offerId], foreignColumns: [workspaceSupplierOffers.workspaceId, workspaceSupplierOffers.id] }),
    check("workspace_supplier_offer_commands_action_check", sql`${table.action} IN ('activate','archive','restore')`),
    check("workspace_supplier_offer_commands_hash_check", sql`${table.requestHash} ~ '^[0-9a-f]{64}$'`),
    index("workspace_supplier_offer_commands_offer_idx").on(table.workspaceId, table.offerId, table.createdAt),
  ],
);
