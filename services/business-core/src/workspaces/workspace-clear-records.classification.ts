// Kept tables with some rows that belong to cleared records: table -> SQL predicate of the rows to delete.
// The same predicates are written in the migration's classification seed (checked by the guard test).
const clearLinked = {
  // A project's site store; the warehouses (no project) stay.
  stock_locations: "project_id IS NOT NULL",
  // Documents of a cleared site worker; staff employee documents stay with their membership.
  hrms_documents: "worker_id IS NOT NULL",
} as const;

