// Go-live reset: which tenant tables `workspace_clear_records()` keeps and which it clears.
//
// Every table with a `workspace_id` column must appear here exactly once. The guard test
// (workspace-clear-records.classification.spec.ts) fails when a migration adds a tenant table
// that is missing, and checks that the SQL classification seeded by the migrations matches this
// list. At run time the SQL function also refuses to run while any tenant table is unclassified.
//
// keep   configuration, people and platform/billing state. Never touched.
// clear  business records and their children. Every row of the workspace is deleted.
// reset  numbering counters for internal record references (enquiry, deal, project, job). The
//        workspace row is deleted, so numbering restarts at 1. Numbers on external documents
//        (quotes, invoices, credit notes, purchase orders) come from `document_sequences`, which
//        is kept, so no number that ever reached a client or supplier is issued twice.
// clear_linked  configuration tables that also hold rows tied to a cleared record. Only the rows
//        matching the reviewed predicate below are deleted; the rest is kept.
// files  `workspace_stored_objects`, the storage ledger. Rows whose object key is still used by a
//        kept table (branding, letterheads, proposal kit pages, gallery, member photos) stay; every
//        other row is removed and its object key is queued for storage deletion.

export type WorkspaceTableDisposition = "keep" | "clear" | "clear_linked" | "reset" | "files";

